import re,html
s=open('issue-01.html').read()
s=re.sub(r'^<!--.*?-->\s*','',s,count=1,flags=re.S)
s=re.sub(r'<!--\s*IMAGE SLOT:\s*(.*?)\.\s*Add your own.*?-->',lambda m:'<p><strong>📷 PHOTO HERE</strong> — '+m.group(1)+'. Click this line, type / → Image, add a photo credit, then delete this line.</p>',s,flags=re.S)
s=re.sub(r'<!--\s*POLL SLOT:\s*(.*?)-->',lambda m:'<p><strong>📊 POLL HERE</strong> — '+m.group(1).strip()+' Type / → Poll, then delete this line.</p>',s,flags=re.S)
s=re.sub(r'<!--.*?-->','',s,flags=re.S)
s=re.sub(r'</?div[^>]*>','',s)
s=re.sub(r'\s+style="[^"]*"','',s)
s=re.sub(r'<span>(.*?)</span>',r'<strong>\1</strong> ',s)
s=re.sub(r'<h3>',r'<h2>',s); s=s.replace('</h3>','</h2>')
s=re.sub(r'<h4>',r'<h3>',s); s=s.replace('</h4>','</h3>')
s=re.sub(r'\n\s*\n','\n',s).strip()
open('issue-01-editable.html','w').write(s)
print(s.count('PHOTO HERE'),s.count('POLL HERE'),len(s))
